import fs from 'fs';

const file = 'apps/web/src/components/GenealogyTree.vue';
const buf = fs.readFileSync(file);
let content = buf;
let fixedCount = 0;

function findAndReplace(targetBytes, replacementBytes) {
  const idx = content.indexOf(targetBytes);
  if (idx < 0) return false;
  console.log('FOUND at', idx);
  const before = content.slice(0, idx);
  const after = content.slice(idx + targetBytes.length);
  content = Buffer.concat([before, replacementBytes, after]);
  return true;
}

